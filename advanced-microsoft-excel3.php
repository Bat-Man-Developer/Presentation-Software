            <h1>📋 AC 2: Copying and Pasting an Object</h1>
            <p style="font-size: 18px; text-align: center; color: var(--text-secondary); margin-bottom: 30px;">
                Duplicating pictures, shapes, or charts cleanly within or across worksheets
            </p>

            <div class="two-column">
                <div>
                    <h2>🔢 Copy &amp; Paste Procedure</h2>
                    <ol class="step-list">
                        <li><strong>Select the Object:</strong> Click the picture, shape, or chart you wish to duplicate.</li>
                        <li><strong>Copy:</strong> Click the <strong>Copy</strong> command on the Home tab (or press <code>Ctrl + C</code>).</li>
                        <li><strong>Choose Target Location:</strong> Click the cell or cells where you want the duplicate placed.</li>
                        <li><strong>Paste:</strong> Click the <strong>Paste</strong> command (or press <code>Ctrl + V</code>). The copied object appears at the highlighted cells while the original stays intact.</li>
                    </ol>
                </div>
