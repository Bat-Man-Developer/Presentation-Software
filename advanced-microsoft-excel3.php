        <!-- Slide 6: File Size, Scanners & Link to File vs. Insert and Link -->
        <div class="slide">
            <h1>💾 File Size, Scanners &amp; Picture Linking Options</h1>
            <p style="font-size: 18px; text-align: center; color: var(--text-secondary); margin-bottom: 30px;">
                Managing workbook file size and understanding embedded vs. linked images
            </p>

            <div class="two-column">
                <div>
                    <h2>🔗 Link to File vs. Insert and Link</h2>
                    <ul>
                        <li><strong>Link to File:</strong> Adds only a link to the external image file. Keeps the Excel workbook small, but if you open the workbook without access to the image's file path, you will see a <strong>red X</strong> instead of the picture.</li>
                        <li><strong>Insert and Link:</strong> Links to the external image <em>and</em> embeds a copy inside the workbook. If the external path is unavailable, the embedded picture still displays!</li>
                        <li><strong>Discard Editing Data:</strong> Under <em>Options → Advanced → Image Size and Quality</em>, do <strong>not</strong> check <em>Discard editing data</em> if you want to keep both the link and artistic edits.</li>
                    </ul>
                </div>
                <div>
                    <div class="tip-box">
                        <h4>📷 Scanners &amp; Cameras</h4>
                        <p style="font-size: 14px; line-height: 1.6;">To insert a photo from a scanner or camera, first transfer and save the image to your computer using the device's software, then use <strong>Insert → Picture</strong>.</p>
                    </div>
                    <div class="warning-box">
                        <h4>⚖️ Controlling Workbook File Size</h4>
                        <p style="font-size: 14px; line-height: 1.6;">Adding high-resolution pictures significantly increases workbook file size. Manage size by choosing appropriate picture <strong>resolution</strong> and <strong>compression</strong> settings.</p>
                    </div>
                </div>
            </div>
        </div>

