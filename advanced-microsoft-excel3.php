        <div class="slide">
            <h1>✂️ AC 2: Cutting and Pasting (Moving) an Object</h1>
            <p style="font-size: 18px; text-align: center; color: var(--text-secondary); margin-bottom: 30px;">
                Relocating objects cleanly without leaving duplicates behind
            </p>

            <div class="two-column">
                <div>
                    <h2>🔢 Cut &amp; Paste Procedure</h2>
                    <ol class="step-list">
                        <li><strong>Select the Object:</strong> Click the object you wish to move.</li>
                        <li><strong>Cut:</strong> Click the <strong>Cut</strong> command on the Home tab (or press <code>Ctrl + X</code>).</li>
                        <li><strong>Choose Target Location:</strong> Select the destination cells (on the same sheet or another worksheet).</li>
                        <li><strong>Paste:</strong> Click the <strong>Paste</strong> command (or press <code>Ctrl + V</code>). The cut object is <strong>removed from its original cells</strong> and moved to the new location.</li>
                    </ol>
                    <div class="tip-box">
                        <strong>💡 Quick Drag Alternative:</strong> To move an object a short distance on the same sheet, hover over it until the four-headed move arrow appears, then click and drag it to its new position.
